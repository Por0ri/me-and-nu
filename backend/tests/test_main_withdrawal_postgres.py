async def withdraw(db):
    user = await db.get(UserAccount, 701)
    session = await db.get(AuthSession, 801)
    return await service.request_withdrawal(db, user=user, session=session, store=None)


async def wait_blocked(factory, pid):
    for _ in range(100):
        async with factory() as observer:
            if await observer.scalar(text("SELECT cardinality(pg_blocking_pids(:pid))"), {"pid": pid}):
                return
        await asyncio.sleep(0.02)
    pytest.fail("Expected a real PostgreSQL row-lock wait")


def state(pg):
    with pg.engine.connect() as db:
        return db.execute(text("SELECT u.account_status, u.withdrawn_at, s.revoked_at, "
            "(SELECT count(*) FROM admin_account WHERE user_id=701) "
            "FROM user_account u JOIN auth_session s ON s.user_id=u.user_id WHERE u.user_id=701")).one()


@pytest.mark.parametrize("revoked", [False, True])
def test_main_blocks_all_existing_grant_history_in_postgres(pg, revoked):
    with pg.engine.begin() as db:
        db.execute(text("INSERT INTO admin_account(user_id,role,revoked_at) VALUES (701,'viewer',:revoked)"),
            {"revoked": datetime.now(timezone.utc) if revoked else None})

    async def scenario():
        engine = create_async_engine(pg.url, poolclass=NullPool)
        try:
            async with async_sessionmaker(engine, expire_on_commit=False)() as db:
                with pytest.raises(ApiError) as error:
                    await withdraw(db)
                assert error.value.code == "WITHDRAWAL_BLOCKED"
        finally:
            await engine.dispose()
    run_async(scenario())
    assert state(pg) == ("active", None, None, 1)


def test_grant_commits_first_withdrawal_waits_then_sees_history(pg):
    async def scenario():
        engine = create_async_engine(pg.url, poolclass=NullPool)
        factory = async_sessionmaker(engine, expire_on_commit=False)
        try:
            async with factory() as granting, factory() as withdrawing:
                # Authentication read predates the concurrently committed grant.
                await withdrawing.get(UserAccount, 701)
                pid = await withdrawing.scalar(text("SELECT pg_backend_pid()"))
                await granting.execute(select(UserAccount).where(UserAccount.user_id == 701).with_for_update())
                await granting.execute(text("INSERT INTO admin_account(user_id,role) VALUES (701,'operator')"))
                task = asyncio.create_task(withdraw(withdrawing))
                try:
                    await wait_blocked(factory, pid)
                    await granting.commit()
                    with pytest.raises(ApiError) as error:
                        await task
                    assert error.value.code == "WITHDRAWAL_BLOCKED"
                finally:
                    if not task.done():
                        task.cancel()
                        await asyncio.gather(task, return_exceptions=True)
        finally:
            await engine.dispose()
    run_async(scenario())
    assert state(pg) == ("active", None, None, 1)


def test_withdrawal_commits_first_grant_waits_then_rejects_inactive_member(pg, monkeypatch):
    async def scenario():
        engine = create_async_engine(pg.url, poolclass=NullPool)
        factory = async_sessionmaker(engine, expire_on_commit=False)
        acquired, proceed = asyncio.Event(), asyncio.Event()
        original = service.lock_user

        async def pause_after_real_lock(db, user_id):
            user = await original(db, user_id)
            acquired.set()
            await asyncio.wait_for(proceed.wait(), 5)
            return user

        monkeypatch.setattr(service, "lock_user", pause_after_real_lock)
        try:
            async with factory() as withdrawing, factory() as granting:
                task = asyncio.create_task(withdraw(withdrawing))
                grant_task = None
                try:
                    await asyncio.wait_for(acquired.wait(), 5)
                    pid = await granting.scalar(text("SELECT pg_backend_pid()"))

                    async def grant_using_checking_lock_contract():
                        # Checking grant/bootstrap read this status under the same
                        # user lock before inserting a new administrator row.
                        status = await granting.scalar(select(UserAccount.account_status)
                            .where(UserAccount.user_id == 701).with_for_update())
                        if status != "active":
                            await granting.rollback()
                            return "ADMIN_TARGET_INACTIVE"
                        await granting.execute(text("INSERT INTO admin_account(user_id,role) VALUES (701,'operator')"))
                        await granting.commit()
                        return "granted"

                    grant_task = asyncio.create_task(grant_using_checking_lock_contract())
                    await wait_blocked(factory, pid)
                    proceed.set()
                    assert await task > datetime.now(timezone.utc)
                    assert await grant_task == "ADMIN_TARGET_INACTIVE"
                finally:
                    proceed.set()
                    pending = [t for t in (task, grant_task) if t is not None and not t.done()]
                    for pending_task in pending:
                        pending_task.cancel()
                    await asyncio.gather(*pending, return_exceptions=True)
        finally:
            await engine.dispose()
    run_async(scenario())
    status, withdrawn, revoked, grants = state(pg)
    assert status == "withdrawn" and withdrawn is not None and revoked is not None and grants == 0


def test_main_schema_without_shared_admin_table_fails_closed(pg):
    with pg.engine.begin() as db:
        db.execute(text("DROP TABLE admin_account"))

    async def scenario():
        engine = create_async_engine(pg.url, poolclass=NullPool)
        try:
            async with async_sessionmaker(engine, expire_on_commit=False)() as db:
                with pytest.raises(ApiError) as error:
                    await withdraw(db)
                assert error.value.code == "WITHDRAWAL_UNAVAILABLE"
                assert not db.in_transaction()  # PostgreSQL aborted read was rolled back.
                assert (await db.get(UserAccount, 701)).account_status == "active"
                assert (await db.get(AuthSession, 801)).revoked_at is None
        finally:
            await engine.dispose()
    run_async(scenario())
