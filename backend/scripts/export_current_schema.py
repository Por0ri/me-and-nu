"""Export the current ORM schema without loading settings or connecting to a DB.

Run with the backend Python environment from any working directory. The output
documents model metadata; Alembic migrations remain the database upgrade path.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

BACKEND_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = BACKEND_ROOT.parent / "docs" / "erd" / "current_schema.sql"
sys.path.insert(0, str(BACKEND_ROOT))

from alembic.script import ScriptDirectory  # noqa: E402
from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import AddConstraint, CreateIndex, CreateTable  # noqa: E402

import app.models  # noqa: E402, F401 -- register every mapped table
from app.db.base import Base  # noqa: E402


def render_schema() -> str:
    """Compile reproducible PostgreSQL DDL from models and local revision files."""
    # ScriptDirectory reads revision files, not alembic/env.py or application
    # settings. No DATABASE_URL, dotenv file, engine or connection is needed.
    heads = sorted(ScriptDirectory(BACKEND_ROOT / "alembic").get_heads())
    dialect = postgresql.dialect()
    tables = sorted(Base.metadata.tables.values(), key=lambda table: table.fullname)
    statements = [
        "-- Generated by backend/scripts/export_current_schema.py; do not edit by hand.",
        "-- Source: current app.models / Base.metadata, including local changes.",
        f"-- Local Alembic head(s): {', '.join(heads) or '(none)'}.",
        f"-- Model tables: {len(tables)}.",
        "-- This is an implementation reference, not a migration or a live DB dump.",
        "-- It does not confirm that any environment has applied the listed revision.",
        "-- Constraint names follow ORM metadata and can differ from migration history.",
        "-- Only SQL server defaults are emitted; Python defaults/onupdate are not triggers.",
        "-- Use Alembic migrations to change existing databases; do not apply this snapshot.",
        "-- Service migration target: f4b8c1d9a620 (onboarding V2 + carousel); do not upgrade all heads.",
        "-- Birth-date policy is deferred: existing birth_date columns/data are preserved.",
        "-- Absence of birth_date here describes ORM metadata, not approval to drop it.",
        "",
        "CREATE EXTENSION IF NOT EXISTS vector;",
    ]

    # Inline PK / UNIQUE / CHECK constraints follow SQLAlchemy's stable model
    # declaration order. Defer every FK so content <-> topic_cluster cycles do
    # not affect table ordering or omit relationships.
    for table in tables:
        ddl = CreateTable(table, include_foreign_key_constraints=[])
        statements.extend(("", str(ddl.compile(dialect=dialect)).strip() + ";"))

    statements.extend(("", "-- Indexes (including partial unique indexes)."))
    for table in tables:
        for index in sorted(table.indexes, key=lambda item: str(item.name)):
            ddl = CreateIndex(index)
            statements.append(str(ddl.compile(dialect=dialect)).strip() + ";")

    statements.extend(("", "-- Foreign keys, added after all tables and unique keys."))
    for table in tables:
        for constraint in sorted(
            table.foreign_key_constraints, key=lambda item: str(item.name)
        ):
            ddl = AddConstraint(constraint, isolate_from_table=False)
            statements.append(str(ddl.compile(dialect=dialect)).strip() + ";")

    # SQLAlchemy emits a space before some line breaks; keep the committed
    # artifact clean and consistent on Windows and Unix.
    lines = (line.rstrip() for line in "\n".join(statements).splitlines())
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=DEFAULT_OUTPUT, help="Snapshot destination."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit with status 1 if the snapshot is missing or differs; write nothing.",
    )
    args = parser.parse_args()
    expected = render_schema()
    output = args.output.resolve()
    if args.check:
        if not output.is_file() or output.read_text(encoding="utf-8") != expected:
            print(f"Schema snapshot is out of date: {output}")
            print("Run this script without --check to regenerate it.")
            return 1
        print(f"Schema snapshot is current: {output}")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Wrote schema snapshot: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
