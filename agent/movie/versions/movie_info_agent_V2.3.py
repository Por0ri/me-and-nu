# ## 셀 3 — 주고받는 값의 모양

from typing import Literal
from pydantic import BaseModel, Field

Topic     = Literal["애니", "영화", "음악"]
Reception = Literal["호평이 많다", "평가가 갈린다", "혹평이 많다"]


class Material(BaseModel):
    tmdb_id: int | None = None
    title: str
    year: int | None = None
    director: str | None = None
    cast: list[str] = []
    genres: list[str] = []
    runtime_min: int | None = None
    rating: str | None = None
    release_date: str | None = None
    upcoming: bool = False              # 아직 개봉 안 한 영화인지
    rerelease: bool = False             # 옛날 영화가 다시 걸린 것인지
    first_release: str | None = None    # 처음 개봉일
    adult: bool = False
    collection_id: int | None = None     # TMDB 컬렉션 번호. 시리즈 용어집을 찾는 데 쓴다
    series: str | None = None            # 용어집 이름. 없으면 None
    synopsis: str = ""
    director_past_works: list[str] = []   # 이 영화보다 앞에 만든 것. 제목(연도)
    director_later_works: list[str] = []  # 이 영화보다 뒤에 만든 것
    source_work: str | None = None
    context: str = ""                   # 주변 이야기. 영화제 · 제작 · 반응
    context_source: str | None = None
    reception: Reception | None = None
    reception_source: str | None = None
    source_links: list[str] = []


class Brief(BaseModel):
    """재료 정리 에이전트가 낸 것. 글쓰기는 이것만 보고 쓴다."""
    headline_fact: str = Field(
        description="언제 나온 무슨 영화인지 한 문장. 재개봉이면 제작 연도와 한국 개봉 연도를 둘 다 넣는다")
    genre_line: str = Field(
        description="갈래를 문장으로 푼 것. 갈래 이름을 붙여서 새 이름을 만들지 않는다")
    characters: list[str] = Field(
        default_factory=list,
        description="인물 이름(배우 이름) 형태. 예: 나인틴 헌드레드(팀 로스)")
    plot: str = Field(description="줄거리를 두세 문장으로 줄인 것. 결말 앞까지")
    runtime_rating: str = Field(
        default="",
        description="상영시간과 관람 등급. 재료에 있는 대로 적는다. 예: 133분 · 15세 이상 관람가")
    origin: str = Field(
        default="", description="이 영화가 어디에서 나왔는지. 감독 이력이나 원작. 없으면 빈칸")
    buzz: str = Field(
        default="", description="기대나 반응. 재료에 있는 것만. 없으면 빈칸")
    dropped: list[str] = Field(
        default_factory=list, description="재료에 있었지만 쓸 수 없다고 본 것과 그 까닭")


class WriteOrder(BaseModel):
    material: Material
    brief: Brief | None = None          # 재료 정리 에이전트가 낸 것
    topic: Topic = "영화"
    tag_topic: Topic | None = None
    temperature: str
    persona: str
    layout: str
    rewrite_note: str | None = None
    previous_body: str | None = None


class Article(BaseModel):
    title: str = Field(description="글 제목. 영화 제목을 그대로 쓰지 않는다")
    body:  str = Field(description="본문. 문단은 빈 줄로 나눈다")
    sources: list[str] = Field(default_factory=list,
                               description="출처 링크. 코드가 채운다. 비워 둬도 된다")


class Screening(BaseModel):
    """재료 판정 에이전트가 내는 값. 등급이 아니라 내용으로 가른다."""
    kind: Literal["극영화", "성인물", "판단 불가"] = Field(
        description="이 영화가 무엇인지")
    why: str = Field(description="그렇게 본 이유 한 문장")
    makers_known: bool = Field(
        description="감독이나 배우에게 이 작품 말고 알려진 이력이 있는지")
    enough: bool = Field(
        description="줄거리와 제작 정보가 글 한 편을 쓸 만큼 있는지")
    note: str = Field(default="", description="눈에 띄는 것. 없으면 빈칸")


class Fix(BaseModel):
    """고치는 에이전트가 낸 것."""
    body: str = Field(description="고친 본문 전체")
    changed: list[str] = Field(default_factory=list, description="무엇을 어떻게 고쳤는지")


class Editorial(BaseModel):
    """편집국장이 낸 것. 고치지 않는다. 통과인지 반려인지와 반려 사유뿐이다."""
    decision: Literal["통과", "반려"]
    issues: list[str] = Field(
        default_factory=list,
        description="반려 사유. 한 줄에 하나. 어느 문장이 왜 걸리는지. 통과면 비운다")
    why: str = Field(description="한 줄 총평")


class JudgeScore(BaseModel):
    topic_fit:    int = Field(ge=1, le=5)
    form_fit:     int = Field(ge=1, le=5)
    element_fit:  int = Field(ge=1, le=5)
    promo:        int = Field(ge=1, le=5)
    completeness: int = Field(ge=1, le=5)
    unsourced_claims: int = Field(ge=0, description="기본 사실이 재료와 어긋난 문장 개수")
    unverified_context: list[str] = Field(
        default_factory=list,
        description="재료에 없는 주변 이야기 문장. 틀린 게 아니라 사람이 확인할 것")
    spoiler: bool
    reason: str


class RunState(BaseModel):
    """한 편을 만드는 동안 모든 마디가 같이 읽고 쓰는 꾸러미.
    LangGraph로 옮기면 이것이 그래프의 상태가 된다."""
    material: Material
    topic: Topic = "영화"
    tag_topic: Topic | None = None
    pick: dict = Field(default_factory=dict)      # 온도 · 시작점 · 배치를 손으로 정할 때
    use_screener: bool = True

    screening: Screening | None = None
    brief: Brief | None = None
    order: WriteOrder | None = None
    article: Article | None = None
    editorial: Editorial | None = None
    shape_bad: list[str] = Field(default_factory=list)
    fix_reasons: list[str] = Field(default_factory=list)   # 고치기가 받을 지적
    judge: JudgeScore | None = None
    verdict: str = ""            # 올림 · 다시쓰기 · 탈락
    verdict_reason: str = ""

    editor_returns: int = 0      # 편집국장 반려 횟수
    shape_rounds: int = 0        # 형태 검사 되돌린 횟수
    judge_rounds: int = 0        # 판정관 되돌린 횟수
    steps: int = 0               # 지나온 마디 수

    status: str = ""             # 대상아님 · 재료부족 · 판단보류 · 올림 · 탈락보관
    reason: str = ""
    log: list[dict] = Field(default_factory=list)

