    rng = random.Random(seed)
    until = (date.today() + timedelta(days=30 * months)).isoformat()
    params = {
        "sort_by": "popularity.desc",
        "without_genres": _without_genres(),
        "include_adult": "false",
        "language": "ko-KR",
        "region": "KR",
        "with_release_type": "1|2|3|4",   # 예정작은 시사회·디지털로만 적힌 경우가 많다
        "release_date.gte": TODAY,
        "release_date.lte": until,
    }
    pool = _discover_pool(params, max_page=15, rng=rng)
    got = _take(pool, n, rng, upcoming=True)
    if len(got) < n:
        print(f"개봉 예정작 후보가 모자라 {len(got)}편만 뽑았다. "
              f"months를 늘리거나 reset_used()로 기록을 비운다")
    return got


