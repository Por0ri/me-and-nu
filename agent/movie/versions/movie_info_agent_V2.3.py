JUDGE_SYSTEM = """
너는 영화 정보 글을 채점한다. 글을 고치지 않는다. 점수와 이유만 낸다.
누가 썼는지 묻지 않는다. 아래 기준만 본다.

[정보 전달이 무엇인지]
이 영화가 무엇이고 언제 나오는지 알려주는 글이다.
볼지 말지 가려 주고 있으면 리뷰다.
무엇을 하려는 작품인지 해석하고 있으면 평론이다.

[항목]

토픽 적합도 (1~5)
  5 처음부터 끝까지 영화 이야기만 한다 / 3 다른 토픽이 섞였다 / 1 영화 이야기가 아니다

유형 일치 (1~5)
  5 이 영화가 무엇이고 언제 나오는지 알려준다. 감상이 한두 문장 섞여 있어도 5점이다
  3 좋은 점과 아쉬운 점을 나눠 대거나, 볼지 말지를 가려 주고 있다
  1 리뷰나 평론이다
  감상이 있다는 이유로 깎지 않는다. 판단이 글의 중심이 됐을 때만 깎는다

요소 포함 (1~5)
  (1) 무엇이 언제 나오는지. 개봉일과 감독이 있는지
  (2) 줄거리
  (3) 이 영화가 어디에서 나왔는지. 감독 이전 작품이나 원작
  기대와 반응은 재료에 있을 때만 센다. 재료에 없으면 글에 없어도 5점이다.
  5 셋이 다 있다 / 3 하나가 빠졌다 / 1 둘 이상 없다

홍보성 (1~5, 높을수록 홍보 성격이 강하다)
  1 사실과 반응을 적고 읽는 사람이 판단하게 둔다
  3 기대를 말하되 그 근거가 있다. 감독의 전작이 어땠고 어느 영화제에서 반응이 어땠다는 식이다
  5 근거 없이 부추긴다. "올해 최고", "놓치면 안 된다", 예매나 개봉관 이야기를 쓴다

글 완성도 (1~5)
  같은 말 반복, 문장 끊김, 앞뒤가 안 맞는 곳을 본다.
  항목을 한 문장에 몰아 적었으면 여기서 깎는다.

[기본 사실이 재료와 어긋난 문장 개수]  → unsourced_claims
  기본 사실은 개봉일 · 감독 · 출연 · 상영시간 · 등급 · 원작 · 인물 이름 · 줄거리 사건이다.
  본문에서 이런 문장을 뽑아 아래 재료와 대조한다.
  재료와 다르게 적은 문장의 개수를 적는다. 재료와 어긋난 것만 센다.
  재료에 없지만 널리 알려진 사실 — 원작, 시리즈 순서, 이야기의 큰 줄기 — 는 여기에 세지 않는다.
  그런 문장은 아래 '재료에 없는 주변 이야기 문장 목록'에 넣는다.
  정보 전달은 사실이 제일 무겁다. 이 개수가 크면 글이 떨어진다.

  아직 개봉하지 않은 영화라면, 본 것처럼 적은 문장도 여기에 더한다.
  장면이 어떻더라, 연기가 어떻더라 같은 문장이다.

  다음 문장은 이 개수에 더하지 않는다.
  - 줄거리를 근거로 댄 설명
  - 주변 이야기. 아래 항목에서 따로 다룬다

[재료에 없는 주변 이야기 문장 목록]  → unverified_context
  주변 이야기는 제작 뒷이야기, 영화제 상영과 반응, 수상, 개봉 뒤 반응이다.
  본문에서 이런 문장을 뽑아 재료의 '주변 이야기' 항목과 대조한다.
  재료에 있으면 넘어간다.
  재료에 없으면 그 문장을 그대로 목록에 적는다. 틀렸다고 보지 않는다. 점수도 깎지 않는다.
  이 목록은 사람이 나중에 확인한다.

[스포일러]
  결말이나 주요 반전을 밝혔으면 참으로 적는다.
  재료의 줄거리에 이미 적혀 있는 내용은 스포일러가 아니다.

[이유]
  점수를 깎은 자리를 문장으로 적는다. 무엇을 고쳐야 하는지 적는다.
"""

judge = Agent(
    JUDGE_MODEL,
    output_type=JudgeScore,
    system_prompt=JUDGE_SYSTEM,
    model_settings=_model_settings,
    retries=1,
)


async def score(article: Article, order: WriteOrder) -> JudgeScore:
    user = (
        f"[배정 토픽] {order.topic}\n"
        f"[배정 유형] 정보 전달\n"
        f"[개봉 전 영화인가] {'그렇다' if order.material.upcoming else '아니다'}\n\n"
        f"[재료]\n{material_to_text(order.material)}\n\n"
        f"[제목]\n{article.title}\n\n"
        f"[본문]\n{article.body}\n\n"
        f"[붙은 출처]\n" + "\n".join(article.sources)
    )
    result = await judge.run(user, usage_limits=_usage_limits)
    return result.output

# ## 셀 11 — 업로드 규칙 (LLM 없이 코드로)

def verdict(s: JudgeScore) -> tuple[str, str]:
    drop, again = [], []

    def band(name, value, pass_line, drop_line):
        if value >= pass_line: return
        if value <= drop_line: drop.append(f"{name} {value}점")
        else:                  again.append(f"{name} {value}점")

    band("토픽 적합도", s.topic_fit,    PASS["topic_fit"],    2)
    band("유형 일치",   s.form_fit,     PASS["form_fit"],     2)
    band("요소 포함",   s.element_fit,  PASS["element_fit"],  2)
    band("글 완성도",   s.completeness, PASS["completeness"], 1)

    if s.promo >= 5:
        drop.append(f"홍보성 {s.promo}점")
    elif s.promo > PASS["promo"]:
        again.append(f"홍보성 {s.promo}점")

    if s.unsourced_claims > UNSOURCED_REWRITE:
        drop.append(f"기본 사실이 재료와 어긋난 문장 {s.unsourced_claims}개")
    elif s.unsourced_claims > UNSOURCED_PASS:
        again.append(f"기본 사실이 재료와 어긋난 문장 {s.unsourced_claims}개")

    if s.spoiler:
        again.append("결말을 밝혔다")

    if drop:  return "탈락", " / ".join(drop) + " — " + s.reason
    if again: return "다시쓰기", " / ".join(again) + " — " + s.reason
    return "올림", ""

# ## 셀 12 — 고치는 에이전트 (Pydantic AI)

FIXER_SYSTEM = """
너는 이미 쓴 글에서 지적된 곳만 고친다. 글을 새로 쓰지 않는다.

문장을 지우지 않는다. 지적된 표현을 다른 표현으로 바꾼다.
  지적: 감상이 섞였다 → 그 문장을 지우는 게 아니라 사실을 말하는 문장으로 바꾼다
  지적: 영문이 남았다 → 그 이름만 한글로 바꾼다
문단 하나가 두 문장 아래로 내려가면 안 된다. 그렇게 되면 지우지 말고 바꾼다.
글 전체 길이를 원래보다 줄이지 않는다. 분량 하한 아래로 내려가면 안 된다.

지적되지 않은 문장은 한 글자도 건드리지 않는다.
문단 순서를 바꾸지 않는다. 문단을 합치거나 나누지 않는다.
지적을 고치느라 다른 곳이 어긋나면, 그 자리까지만 최소로 손본다.

분량이 지적됐으면 그 문단 안에서 늘리거나 줄인다. 새 문단을 만들지 않는다.
문장이 짧다고 지적됐으면 앞뒤 문장을 이어 붙인다. 내용을 더 넣지 않는다.
영문 표기가 남았다고 지적됐으면 그 이름만 한글로 바꾼다.
사실이 틀렸다고 지적됐으면 [정리된 재료]에 맞게 그 문장만 고친다.
재료에 없으면 그 문장을 뺀다. 지어내서 채우지 않는다.

문체는 원래 글을 따른다. 존댓말을 쓰지 않는다. 느낌표를 쓰지 않는다.
무엇을 어떻게 고쳤는지 한 줄씩 적는다.
"""

fixer = Agent(
    FIXER_MODEL,
    output_type=Fix,
    system_prompt=FIXER_SYSTEM,
    model_settings=_model_settings,
    retries=1,
)


async def fix(article: Article, order: WriteOrder, reasons: list[str]) -> Article:
    body = (brief_to_text(order.brief) if order.brief
            else material_to_text(order.material))
    user = (
        "[지적된 것]\n" + "\n".join(f"- {r}" for r in reasons) +
        f"\n\n[분량] {MIN_CHARS}자에서 {MAX_CHARS}자 사이다." +
        f"\n\n[정리된 재료]\n{body}" +
        f"\n\n[고칠 글]\n{article.body}"
    )
    out = (await fixer.run(user, usage_limits=_usage_limits)).output
    return Article(title=article.title, body=out.body,
                   sources=list(order.material.source_links))

# ## 셀 13 — 한 편 돌리기: 상태 하나 · 마디 · 갈림길

# 마디(node)는 상태를 받아 자기 칸만 채우고 돌려준다.
# 갈림길(edge)은 상태를 보고 다음 마디 이름만 돌려준다.
# 돌리는 건 맨 아래 run_graph 하나다.
# LangGraph로 옮길 때는 마디를 add_node, 갈림길을 add_conditional_edges에 그대로 꽂는다.

END = "끝"


def _finish(st: RunState, status: str, reason: str = "") -> RunState:
    st.status, st.reason = status, reason
    return st


# ── 마디 ──────────────────────────────────────────────────
def n_gate(st: RunState) -> RunState:
    """코드로 명백한 것만 뺀다."""
    for check, status in ((genre_ok, "대상아님"), (date_ok, "대상아님"),
                          (enough_material, "재료부족")):
        ok, why = check(st.material)
        if not ok:
            return _finish(st, status, why)
    return st


async def n_screen(st: RunState) -> RunState:
    """재료 판정 — 내용으로 가른다."""
    sc = await screen(st.material)
    st.screening = sc
    st.log.append({"단계": "재료판정", "결과": sc.kind, "이유": sc.why,
                   "만든 사람 이력": sc.makers_known, "재료 충분": sc.enough})
    if sc.kind == "성인물":
        return _finish(st, "대상아님", f"성인물로 판정됐다 — {sc.why}")
    if sc.kind == "판단 불가":
        return _finish(st, "판단보류", f"판단이 안 선다 — {sc.why}")
    if not sc.enough:
        return _finish(st, "재료부족", f"재료가 얇다 — {sc.why}")
    if not sc.makers_known:
        return _finish(st, "대상아님", f"만든 사람 이력을 확인할 수 없다 — {sc.why}")
    return st


async def n_prepare(st: RunState) -> RunState:
    """재료 정리 — 갈래 · 인물 · 개봉일 · 기사를 정리하고 주문을 만든다."""
    brief = await prepare(st.material)
    st.brief = brief
    st.log.append({"단계": "재료정리", "한 줄": brief.headline_fact,
                   "갈래": brief.genre_line, "인물": brief.characters,
                   "기대·반응 있음": bool(brief.buzz), "뺀 것": brief.dropped})
    st.order = WriteOrder(
        material=st.material, brief=brief, topic=st.topic, tag_topic=st.tag_topic,
        temperature=st.pick.get("temperature") or random.choice(TEMPERATURES),
        persona=st.pick.get("persona") or random.choice(PERSONAS),
        layout=st.pick.get("layout") or random.choice(LAYOUTS),
    )
    return st


async def n_write(st: RunState) -> RunState:
    """글쓰기. 편집국장 반려가 있으면 그 사유와 앞 글을 받아 다시 쓴다."""
    st.article = await write(st.order)
    st.order.rewrite_note = None
    st.order.previous_body = None
    return st


async def n_editor(st: RunState) -> RunState:
    """편집국장 — 통째로 읽고 통과 · 반려."""
    ed = await edit_review(st.article, st.order)
    st.editorial = ed
    st.log.append({"단계": "편집국장", "회차": st.editor_returns,
                   "결과": ed.decision, "이유": ed.why, "사유": ed.issues})
    if ed.decision == "반려":
        st.editor_returns += 1
        st.order.rewrite_note = "\n".join(f"- {i}" for i in ed.issues)
        st.order.previous_body = st.article.body
    return st


def n_shape(st: RunState) -> RunState:
    """형태 검사 — 코드."""
    st.shape_bad = shape_check(st.article, st.order)
    if st.shape_bad:
        st.log.append({"단계": "형태검사", "회차": st.shape_rounds, "결과": st.shape_bad})
        st.fix_reasons = list(st.shape_bad)
    return st


async def n_fix(st: RunState) -> RunState:
    """고치기 — 형태 검사나 판정관이 넘긴 지적만 손본다."""
    st.article = await fix(st.article, st.order, st.fix_reasons)
    st.fix_reasons = []
    return st


async def n_rewrite_for_shape(st: RunState) -> RunState:
    """형태가 계속 걸릴 때 처음부터 다시 쓴다. 앞 글은 안 준다."""
    st.order.rewrite_note = " / ".join(st.shape_bad)
    st.order.previous_body = None
    st.article = await write(st.order)
    st.order.rewrite_note = None
    return st


async def n_judge(st: RunState) -> RunState:
    """판정관 — 점수. 통과선은 코드(verdict)가 본다."""
    sc = await score(st.article, st.order)
    st.judge = sc
    st.verdict, st.verdict_reason = verdict(sc)
    st.log.append({"단계": "판정관", "회차": st.judge_rounds,
                   "온도": st.order.temperature, "시작점": st.order.persona,
                   "배치": st.order.layout,
                   "점수": sc.model_dump(exclude={"unverified_context", "reason"}),
                   "확인 필요한 주변 이야기": sc.unverified_context,
                   "결과": st.verdict, "이유": st.verdict_reason})
    if st.verdict == "다시쓰기":
        st.fix_reasons = [st.verdict_reason]
    return st


# ── 갈림길 — 다음 마디 이름만 돌려준다 ──────────────────────
def after_gate(st: RunState) -> str:
    if st.status: return END
    return "재료판정" if st.use_screener else "재료정리"

def after_screen(st: RunState) -> str:
    return END if st.status else "재료정리"

def after_prepare(st: RunState) -> str:
    return "글쓰기"

def after_write(st: RunState) -> str:
    return "편집국장"

def after_editor(st: RunState) -> str:
    if st.editorial.decision == "통과":
        return "형태검사"
    if st.editor_returns > MAX_EDITOR_RETURN:
        _finish(st, "탈락보관", f"편집국장 반려 {MAX_EDITOR_RETURN}회 초과 — "
                + " / ".join(st.editorial.issues))
        return END
    return "글쓰기"                     # 작가가 반려 사유와 앞 글을 받아 다시 쓴다

def after_shape(st: RunState) -> str:
    if not st.shape_bad:
        return "판정관"
    if st.shape_rounds >= MAX_REWRITE:
        _finish(st, "탈락보관", f"형태 검사 {MAX_REWRITE}회 초과 — " + " / ".join(st.shape_bad))
        return END
    st.shape_rounds += 1
    if is_structure_problem(st.shape_bad) and st.shape_rounds >= 2:
        return "형태다시쓰기"
    return "고치기"

def after_fix(st: RunState) -> str:
    return "형태검사"

def after_shape_rewrite(st: RunState) -> str:
    return "형태검사"

def after_judge(st: RunState) -> str:
    if st.verdict == "올림":
        _finish(st, "올림"); return END
    if st.verdict == "탈락":
        _finish(st, "탈락보관", st.verdict_reason); return END
    if st.judge_rounds >= MAX_REWRITE:
        _finish(st, "탈락보관", f"판정관 다시쓰기 {MAX_REWRITE}회 초과 — {st.verdict_reason}")
        return END
    st.judge_rounds += 1
    return "고치기"                     # 고친 뒤 형태검사 → 판정관으로 다시 간다


# ── 그래프 — 마디 이름 : (마디 함수, 갈림길 함수) ────────────
GRAPH = {
    "거르기":       (n_gate,              after_gate),
    "재료판정":     (n_screen,            after_screen),
    "재료정리":     (n_prepare,           after_prepare),
    "글쓰기":       (n_write,             after_write),
    "편집국장":     (n_editor,            after_editor),
    "형태검사":     (n_shape,             after_shape),
    "고치기":       (n_fix,               after_fix),
    "형태다시쓰기":  (n_rewrite_for_shape, after_shape_rewrite),
    "판정관":       (n_judge,             after_judge),
}
START = "거르기"


async def run_graph(st: RunState) -> RunState:
    node = START
    while node != END:
        st.steps += 1
        if st.steps > MAX_STEPS:
            return _finish(st, "탈락보관", f"마디 {MAX_STEPS}개 상한을 넘었다")
        fn, edge = GRAPH[node]
        st = await fn(st) if inspect.iscoroutinefunction(fn) else fn(st)
        node = edge(st)
    return st


async def produce(material: Material, topic="영화", tag_topic=None,
                  temperature=None, persona=None, layout=None,
                  use_screener: bool = True) -> dict:
    """한 편을 만든다. 돌려주는 모양은 V1.x와 같다(show · save_md가 그대로 쓴다)."""
    st = RunState(material=material, topic=topic, tag_topic=tag_topic,
                  use_screener=use_screener,
                  pick={"temperature": temperature, "persona": persona, "layout": layout})
    st = await run_graph(st)
    out = {"상태": st.status, "이유": st.reason, "로그": st.log,
           "판정": st.screening, "마디수": st.steps}
    if st.article:
        out.update({"글": st.article, "주문": st.order,
                    "확인필요": st.judge.unverified_context if st.judge else []})
    return out


