GLOSSARIES: dict = json.loads(GLOSSARY_JSON)


def find_series(m: "Material") -> str | None:
    """이 영화가 어느 시리즈 용어집에 드는지. 컬렉션 번호 먼저, 그다음 제목."""
    for name, g in GLOSSARIES.items():
        if m.collection_id and m.collection_id in g.get("tmdb_collections", []):
            return name
    for name, g in GLOSSARIES.items():
        if any(k in (m.title or "") for k in g.get("title_keys", [])):
            return name
    return None


def glossary_text(series: str | None, with_meaning: bool = True) -> str:
    """재료 정리 · 글쓰기에 붙일 표기표. 없으면 빈 문자열."""
    if not series or series not in GLOSSARIES:
        return ""
    g = GLOSSARIES[series]
    rows = []
    for fixed, wrong, alias, kind, meaning in g["항목"]:
        line = f"- {fixed}"
        if alias:
            line += f"  (별칭: {' · '.join(alias)})"
        if wrong:
            line += f"  (이렇게 쓰지 않는다: {' · '.join(wrong)})"
        if with_meaning:
            line += f"  — {kind}. {meaning}"
        rows.append(line)
    return (f"[{series} 표기표 — 기준: {g['기준']}]\n"
            "아래 정식 표기만 쓴다. 괄호 안 표기가 재료에 있으면 정식 표기로 바꾼다.\n"
            + "\n".join(rows))


def _glossary_bad_forms(series: str | None) -> list[tuple[str, str]]:
    """코드 검사용. (틀린 표기, 정식 표기) 쌍. 별칭은 안 잡는다. 짧은 말도 뺀다."""
    if not series or series not in GLOSSARIES:
        return []
    g = GLOSSARIES[series]
    fixed_all = [row[0] for row in g["항목"]]
    pairs = []
    for fixed, wrong, _, _, _ in g["항목"]:
        for o in wrong:
            is_latin = bool(re.search(r"[A-Za-z]", o))
            if not is_latin and len(o) < 3:
                continue                      # 샘 · 제국 · 듄 같은 것은 못 잡는다
            if any(o in f for f in fixed_all):
                continue                      # 정식 표기 안에 든 말은 건드리지 않는다
            pairs.append((o, fixed))
    return pairs


def glossary_check(body: str, series: str | None) -> list[str]:
    bad = []
    for wrong, right in _glossary_bad_forms(series):
        if wrong in body:
            bad.append(f"표기가 틀렸다: '{wrong}' → '{right}'")
    return bad

