def _print_log(mat, r):
    tag = f" — {r.get('이유', '')}" if r.get("이유") else ""
    print(f"[{mat.title}] {r['상태']}{tag}")
    for row in r["로그"]:
        st = row["단계"]
        if st == "형태검사":
            print(f"    {st} {row['회차']}회: {' / '.join(row['결과'])}")
        elif st == "판정관":
            print(f"    {st} {row['회차']}회: {row['결과']} — {row['이유']}")
        elif st == "편집국장":
            print(f"    {st} {row['회차']}회: {row['결과']} — {row['이유']}")
            for i in row.get("사유", []):
                print(f"      · {i}")
        elif st == "재료판정":
            print(f"    {st}: {row['결과']} — {row['이유']}")
        elif st == "재료정리":
            print(f"    {st}: {row['한 줄']}")
            if row["뺀 것"]:
                print(f"      뺀 것: {row['뺀 것']}")


async def cmd_batch(cands, label: str):
    """셀 17 · 18 — 뽑힌 후보를 차례로 돌리고 저장한다"""
    print(f"{label}:")
    for c in cands:
        print(f" - {c['title']} ({c['year']})  id={c['id']}")
    print()

    for c in cands:
        mat = fetch_material_by_id(c["id"], fallback_title=c["title"] or "")
        r = await produce(mat)
        _print_log(mat, r)
        if r.get("글"):
            save_md(r)

    print("\n저장된 파일:")
    for p in sorted(OUT_DIR.glob("*.md")):
        print(" -", p.name)
    download_all()


def main(argv=None):
    import argparse
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")     # 윈도우 콘솔에서 — · 같은 글자가 깨지지 않게

    ap = argparse.ArgumentParser(description="영화 정보 전달 에이전트")
    sub = ap.add_subparsers(dest="cmd", required=True)

    a = sub.add_parser("material", help="재료만 가져와 본다 (셀 15)")
    a.add_argument("title"); a.add_argument("year", type=int)

    a = sub.add_parser("one", help="한 편 돌린다 (셀 16)")
    a.add_argument("title"); a.add_argument("year", type=int)

    a = sub.add_parser("released", help="개봉작 무작위 N편 (셀 17)")
    a.add_argument("n", type=int, nargs="?", default=5)

    a = sub.add_parser("upcoming", help="개봉 전 영화 무작위 N편 (셀 18)")
    a.add_argument("n", type=int, nargs="?", default=5)

    args = ap.parse_args(argv)
    if args.cmd == "material":
        cmd_material(args.title, args.year)
    elif args.cmd == "one":
        asyncio.run(cmd_one(args.title, args.year))
    elif args.cmd == "released":
        asyncio.run(cmd_batch(pick_released(args.n), "뽑힌 영화"))
    elif args.cmd == "upcoming":
        asyncio.run(cmd_batch(pick_upcoming(args.n), "뽑힌 개봉 예정작"))


if __name__ == "__main__":
    main()
