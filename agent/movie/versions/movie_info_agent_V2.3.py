# ## 셀 9 — 형태 검사 (LLM 없이 코드로)

STAR_MARKS = ("★", "☆", "⭐", "/10", "/5", "점 만점")
PUSH_WORDS = ("예매", "극장에서 꼭", "놓치지 마", "강력 추천", "무조건 봐", "개봉관")
HYPE_WORDS = ("역대급", "올해 최고", "놓치면 후회", "대작의 귀환", "최고의 기대작",
              "반드시 봐야", "필람")
JUDGE_WORDS = ("아쉬운 점", "좋은 점", "장점은", "단점은", "추천하는 사람",
               "이런 사람에게")
RECEPTION_KEYS = ("호평", "혹평", "평이 갈", "평가가 갈", "호불호",
                  "평점", "관객 평", "반응이", "평이 박")
CONJ_OPENERS = ("그래서", "그러나", "다만", "하지만", "또한", "그럼에도", "그리고",
                "그만큼", "그래도")

_POLITE = re.compile(r"(습니다|입니다|합니다|됩니다|세요|해요|에요|예요|네요|거죠|죠)\s*[.?!\n]")
_LATIN_RUN = re.compile(r"[A-Za-z][A-Za-z\u2019'.\-]*(?:\s+[A-Za-z][A-Za-z\u2019'.\-]*)*")
# 한국어에서 그대로 쓰는 말이다. 영문 이름 검사에서 뺀다
ALLOWED_LATIN = {"SF", "OST", "CG", "VFX", "3D", "4D", "2D", "IMAX", "OTT", "TV",
                 "AI", "DVD", "IP", "PD", "MC", "NG", "CF", "PPL", "B급", "SNS",
                 "HD", "UHD", "4K", "VOD", "MZ", "K", "N차"}
META_WORDS = ("재료에", "제시되지 않", "확인되지 않", "알려진 바 없", "정보가 없",
              "공개된 자료", "나와 있지 않", "TMDB", "평점 분포", "평점 기준", "미상")
UNKNOWN_PAREN = re.compile(r"\((?:배우 |성우 )?(?:미상|알 수 없음|불명|미확인|없음)\)")
FUTURE_RELEASE = re.compile(r"개봉(?:한다|할 예정|을 앞두|을 기다)")
PAST_RELEASE   = re.compile(r"개봉(?:했다|됐다|되었다)")
CAST_LIST = re.compile(r"(?:[가-힣]{2,5} [가-힣]{2,7}, ){2,}[가-힣]{2,5} [가-힣]{2,7}")
HEDGE_ENDS = re.compile(r"(에 가깝다|인 셈이다|할 만하다|는 편이다|일 수 있다|로 보인다|로 느껴진다)[.]")
HEDGE_MAX = 1
NEUNDE_MAX_PER_PARA = 1

# 끊김 검사 — 임시값. 글이 짧아서 리뷰보다 낮게 잡았다
CHOP_AVG_MIN      = 28
CHOP_SHORT_LEN    = 20
CHOP_SHORT_RUN    = 3
CHOP_SAME_END_RUN = 4
COPY_MIN_LEN      = 14

STRUCTURE_HINTS = ("너무 짧다", "연달아", "끝맺음", "그대로 옮긴", "같은 말로 시작",
                   "접속사", "늘어놓았다", "문단이 많다", "문단이 적다",
                   "예시 문장", "흐리는", "는데")


def _latin_leftovers(body: str) -> list[str]:
    """본문에 남은 영문 덩어리를 찾는다.
    SF처럼 한국어에서 그대로 쓰는 말은 안 잡는다."""
    out = []
    for t in _LATIN_RUN.findall(body):
        t = t.strip()
        if len(t.replace(" ", "")) < 2:
            continue
        if all(w in ALLOWED_LATIN for w in t.split()):
            continue
        out.append(t)
    return out


def _sentences(body: str) -> list[str]:
    return [t.strip() for t in re.split(r"(?<=[.?!])\s+", body) if t.strip()]


def _reception_sentences(body: str) -> list[str]:
    return [s for s in re.split(r"[.!?\n]", body)
            if any(k in s for k in RECEPTION_KEYS)]


def _choppiness(body: str) -> list[str]:
    sents = _sentences(body)
    if len(sents) < 5:
        return []
    bad = []
    avg = sum(len(t) for t in sents) / len(sents)
    if avg < CHOP_AVG_MIN:
        bad.append(f"문장이 너무 짧다 (평균 {avg:.0f}자). 앞뒤를 이어 쓴다")
    run, max_run = 0, 0
    for t in sents:
        run = run + 1 if len(t) < CHOP_SHORT_LEN else 0
        max_run = max(max_run, run)
    if max_run >= CHOP_SHORT_RUN:
        bad.append(f"짧은 문장이 {max_run}개 연달아 나온다. 사이를 이어 쓴다")
    ends = [t.rstrip(".?!")[-2:] for t in sents]
    same, max_same = 1, 1
    for a, b in zip(ends, ends[1:]):
        same = same + 1 if a == b else 1
        max_same = max(max_same, same)
    if max_same >= CHOP_SAME_END_RUN:
        bad.append(f"같은 끝맺음이 {max_same}문장 연달아 나온다. 끝을 바꿔 쓴다")
    return bad


def _copied_spans(body: str, material_text: str) -> list[str]:
    src = re.sub(r"\s+", "", material_text)
    txt = re.sub(r"\s+", "", body)
    found, i = [], 0
    while i + COPY_MIN_LEN <= len(txt):
        piece = txt[i:i + COPY_MIN_LEN]
        if piece in src:
            j = i + COPY_MIN_LEN
            while j < len(txt) and txt[i:j + 1] in src:
                j += 1
            found.append(txt[i:j])
            i = j
        else:
            i += 1
    return found


def _paragraph_openers(body: str) -> list[str]:
    paras = [p.strip() for p in body.split("\n\n") if p.strip()]
    heads = [re.split(r"[\s,]", p, maxsplit=1)[0] for p in paras]
    bad = []
    for a, b in zip(heads, heads[1:]):
        if a == b:
            bad.append(f"문단 두 개가 같은 말로 시작한다 ({a})")
            break
    conj = sum(1 for h in heads if h in CONJ_OPENERS)
    if conj >= 2:
        bad.append(f"문단 첫머리에 접속사가 {conj}번 나온다. 접속사 없이 시작한다")
    return bad


def _example_text() -> str:
    """프롬프트에 든 예시 문장. 본문이 이걸 그대로 옮기면 잡는다."""
    chunks = [COMMON, FORM_INFO, STANCE] + list(TEMPERATURE.values())
    lines = []
    for c in chunks:
        for ln in c.splitlines():
            t = ln.strip()
            if t.startswith(("예:", "이음:", "토막:", "안 됨:", "됨:")):
                lines.append(t.split(":", 1)[-1].strip())
    return " ".join(lines)


EXAMPLE_TEXT = _example_text()


def is_structure_problem(reasons: list[str]) -> bool:
    return any(h in r for r in reasons for h in STRUCTURE_HINTS)


def shape_check(article: Article, order: WriteOrder) -> list[str]:
    bad = []
    body = article.body
    m = order.material

    if not article.title.strip():
        bad.append("제목이 비었다")
    if article.title.strip() == m.title:
        bad.append("제목이 영화 제목과 똑같다")

    n = len(body)
    if n < MIN_CHARS:
        bad.append(f"글이 짧다 ({n}자, 최소 {MIN_CHARS}자)")
    if n > MAX_CHARS:
        bad.append(f"글이 길다 ({n}자, 최대 {MAX_CHARS}자)")

    if m.source_links and not article.sources:
        bad.append("출처가 하나도 없다")

    bad += glossary_check(body, m.series)

    # 정보 전달에 반드시 들어가야 하는 것
    if m.title not in body and m.title not in article.title:
        bad.append(f"영화 제목이 본문에 없다 ({m.title})")
    if m.release_date and m.release_date[:4] not in body:
        bad.append("개봉 연도가 본문에 없다")
    if m.director:
        # 감독은 재료가 영문일 수 있어 성(마지막 낱말)만으로도 본다. 둘이면 둘 다 있어야 한다
        for name in [d.strip() for d in m.director.split(",") if d.strip()]:
            last = name.split()[-1]
            if name not in body and last not in body:
                bad.append(f"감독 이름이 본문에 없다 ({name})")

    for mark in STAR_MARKS:
        if mark in body:
            bad.append(f"점수 표시가 들어갔다 ({mark})")
            break
    for w in PUSH_WORDS:
        if w in body:
            bad.append(f"보러 가라고 부추기는 말이 들어갔다 ({w})")
            break
    for w in HYPE_WORDS:
        if w in body:
            bad.append(f"근거 없이 세게 말하는 표현이 들어갔다 ({w})")
            break
    for w in JUDGE_WORDS:
        if w in body:
            bad.append(f"리뷰가 하는 일을 했다 ({w}). 정보 전달은 가려 주지 않는다")
            break

    if "!" in body:
        bad.append("느낌표가 들어갔다")

    latin = _latin_leftovers(body)
    if latin:
        bad.append(f"영문 표기가 남았다 ({', '.join(latin[:3])}). 한글로 옮겨 쓴다")

    for w in META_WORDS:
        if w in body:
            bad.append(f"재료에 무엇이 없는지를 독자에게 말했다 ({w}). 없으면 그냥 안 쓴다")
            break

    polite = len(_POLITE.findall(body))
    if polite:
        bad.append(f"존댓말이 들어갔다 ({polite}곳). 문어체 반말로 쓴다")

    hedges = HEDGE_ENDS.findall(body)
    if len(hedges) > HEDGE_MAX:
        bad.append(f"판단을 흐리는 끝맺음이 {len(hedges)}번 나온다. 판단은 '~다'로 끝낸다")

    for p in body.split("\n\n"):
        k = len(re.findall(r"(?:는데|인데),", p))
        if k > NEUNDE_MAX_PER_PARA:
            bad.append(f"한 문단에 '~는데'로 잇는 문장이 {k}개다. 문단마다 하나다")
            break

    bad += _choppiness(body)
    bad += _paragraph_openers(body)

    copied = _copied_spans(body, m.synopsis + " " + m.context)
    if copied:
        bad.append(f"재료 문장을 그대로 옮긴 곳이 {len(copied)}군데다. 예: '{copied[0][:20]}…'")

    ex = _copied_spans(body, EXAMPLE_TEXT)
    if ex:
        bad.append(f"프롬프트 예시 문장을 그대로 옮겼다. 예: '{ex[0][:20]}…'")

    for sent in _sentences(body):
        bare = re.sub(r"\([^)]*\)", "", sent)      # 괄호 안 배우 이름은 안 센다
        if sum(1 for c in m.cast if c in bare) >= 3 or CAST_LIST.search(bare):
            bad.append("출연진 이름을 한 문장에 늘어놓았다")
            break

    if UNKNOWN_PAREN.search(body):
        bad.append("괄호 안에 '미상' 같은 재료 표시가 남았다. 모르면 괄호를 뺀다")

    if not m.upcoming and FUTURE_RELEASE.search(body):
        bad.append("이미 개봉한 영화를 개봉 예정처럼 썼다. 시제를 과거로 쓴다")
    if m.upcoming and PAST_RELEASE.search(body):
        bad.append("아직 개봉 안 한 영화를 개봉한 것처럼 썼다")

    for a in m.genres:                              # 갈래를 붙여서 새 이름을 만든 경우
        for b2 in m.genres:
            if a != b2 and f"{a} {b2}" in body:
                bad.append(f"갈래 이름을 붙여서 새 이름을 만들었다 ({a} {b2})")
                break
        else:
            continue
        break

    said = _reception_sentences(body)
    if m.reception is None and said and not m.context:
        bad.append("재료에 반응이 없는데 반응을 썼다")
    if said and re.search(r"\d+\s*(점|%|명)", " ".join(said)):
        bad.append("반응을 숫자로 적었다. 말로 바꿔 쓴다")

    return bad

