TODAY = date.today().isoformat()


def _tmdb(path: str, **params):
    params["api_key"] = TMDB_KEY
    params.setdefault("language", "ko-KR")
    r = requests.get(f"{TMDB}{path}", params=params, timeout=20)
    r.raise_for_status()
    return r.json()


def search_movie(title: str, year: int | None = None) -> int | None:
    params = {"query": title}
    if year:
        params["year"] = year
    hits = _tmdb("/search/movie", **params).get("results", [])
    if not hits and year:
        hits = _tmdb("/search/movie", query=title).get("results", [])
    return hits[0]["id"] if hits else None


KR_RELEASE_TYPES = (2, 3)        # 2는 극장 제한 개봉, 3은 극장 정식 개봉


def _kr_release(movie_id: int) -> dict:
    """한국 극장 개봉 기록을 전부 본다.
    2020년 뒤 기록이 있으면 그 날짜를 쓴다. 옛날 영화가 재개봉으로 들어오게 하려는 것이다."""
    out = {"date": None, "first": None, "rerelease": False, "cert": None}
    try:
        data = _tmdb(f"/movie/{movie_id}/release_dates", language="en-US")
    except Exception:
        return out
    for row in data.get("results", []):
        if row.get("iso_3166_1") != "KR":
            continue
        dates = []
        for rel in row.get("release_dates", []):
            d = (rel.get("release_date") or "")[:10]
            if rel.get("type") in KR_RELEASE_TYPES and d:
                dates.append(d)
            if rel.get("certification") and not out["cert"]:
                out["cert"] = rel["certification"]
        dates.sort()
        if dates:
            recent = [d for d in dates if d >= SINCE_DATE]
            out["first"] = dates[0]
            out["date"] = recent[0] if recent else dates[0]
            out["rerelease"] = bool(recent) and dates[0] < SINCE_DATE
        return out
    return out


def _director_works(person_id: int, exclude_id: int, this_date: str,
                    limit: int = 4) -> tuple[list[str], list[str]]:
    """감독의 다른 작품을 연도와 함께 돌려준다. 이 영화보다 앞 것과 뒤 것을 나눈다."""
    try:
        data = _tmdb(f"/person/{person_id}/movie_credits")
    except Exception:
        return [], []
    works = [c for c in data.get("crew", [])
             if c.get("job") == "Director" and c.get("id") != exclude_id
             and c.get("release_date") and c.get("title")]
    works.sort(key=lambda c: c["release_date"], reverse=True)
    before = [f"{c['title']}({c['release_date'][:4]})" for c in works
              if this_date and c["release_date"] < this_date][:limit]
    after  = [f"{c['title']}({c['release_date'][:4]})" for c in works
              if this_date and c["release_date"] > this_date][:limit]
    return before, after


