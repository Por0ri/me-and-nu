def to_markdown(out: dict) -> str:
    a, o = out.get("글"), out.get("주문")
    m = o.material if o else None

    lines = []
    if a:
        lines += [f"# {a.title}", ""]
    if m:
        lines += [f"**영화** {m.title}" + (f" ({m.year})" if m.year else "")
                  + (" · 개봉 전" if m.upcoming else ""), ""]
    lines += [f"**상태** {out['상태']} · **버전** {VERSION} · **유형** {FORM}"]
    if out.get("이유"):
        lines += [f"**이유** {out['이유']}"]
    if o:
        lines += [f"**온도** {o.temperature} · **시작점** {o.persona} · **배치** {o.layout}"]
    if out.get("판정"):
        sc = out["판정"]
        lines += [f"**재료 판정** {sc.kind} — {sc.why}"]
        if sc.note:
            lines += [f"**눈에 띄는 것** {sc.note}"]
    lines += [f"**만든 날** {TODAY}", "", "---", ""]

    if a:
        lines += [a.body.strip(), "", "---", "", "## 출처", ""]
        lines += [f"- {u}" for u in a.sources]
        lines += [""]

    if out.get("확인필요"):
        lines += ["## 사람이 확인할 문장 — 재료에 없는 주변 이야기", ""]
        lines += [f"- [ ] {t}" for t in out["확인필요"]]
        lines += [""]

    if m:
        lines += ["## 재료", "", "```", material_to_text(m), "```", ""]

    lines += ["## 로그", ""]
    for row in out["로그"]:
        head = f"- {row['단계']}"
        if "회차" in row:
            head += f" {row['회차']}회"
        if row.get("결과"):
            head += f" · 결과 {row['결과']}"
        lines += [head]
        if row.get("이유"):
            lines += [f"  - 이유: {row['이유']}"]
        if row.get("점수"):
            lines += [f"  - 점수: `{json.dumps(row['점수'], ensure_ascii=False)}`"]
    return "\n".join(lines)


def save_md(out: dict) -> Path:
    o = out.get("주문")
    title = out["글"].title if out.get("글") else "글없음"
    movie = o.material.title if o else "영화없음"
    path = OUT_DIR / f"{_safe_name(movie)}__{_safe_name(title)}.md"
    path.write_text(to_markdown(out), encoding="utf-8")
    return path


def download_all():
    """out/movie_info 폴더를 zip 하나로 묶는다. 콜랩의 files.download 자리다."""
    import shutil
    zip_path = shutil.make_archive(str(OUT_DIR), "zip", OUT_DIR)
    print("zip:", zip_path)
    return zip_path


