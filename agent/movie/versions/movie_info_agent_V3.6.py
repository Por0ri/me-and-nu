TMDB_GENRE_ID = {"다큐멘터리": 99, "가족": 10751, "애니메이션": 16, "TV 영화": 10770}
DISCOVER_MIN_VOTES = 50
# region=KR과 같이 쓰면 release_date.desc가 한국 개봉일 순이 된다
DISCOVER_SORTS = ["popularity.desc", "vote_count.desc", "release_date.desc"]

USED: set[int] = set()   # 이번 세션에서 이미 뽑은 영화


def _without_genres() -> str:
    return ",".join(str(TMDB_GENRE_ID[g]) for g in EXCLUDE_GENRES if g in TMDB_GENRE_ID)


def _discover_pool(params: dict, max_page: int, rng) -> list[dict]:
    """여러 페이지에서 후보를 모아 온다. 한 페이지만 보면 같은 것만 돈다."""
    pool, pages = [], list(range(1, max_page + 1))
    rng.shuffle(pages)
    for page in pages[:6]:
        try:
            data = _tmdb("/discover/movie", page=page, **params)
        except Exception:
            continue
        rows = data.get("results", [])
        pool += [r for r in rows if r.get("overview") and r["id"] not in USED]
        if data.get("total_pages", 1) < page:
            break
    return pool


def _take(pool: list[dict], n: int, rng, upcoming: bool) -> list[dict]:
    rng.shuffle(pool)
    picked = []
    for r in pool:
        if r["id"] in USED:
            continue
        USED.add(r["id"])
        picked.append({"id": r["id"], "title": r.get("title"),
                       "year": (r.get("release_date") or "")[:4], "upcoming": upcoming})
        if len(picked) == n:
            break
    return picked


def pick_released(n: int = 5, seed: int | None = None) -> list[dict]:
    """2020년 1월 1일 뒤에 개봉한 영화를 무작위로 뽑는다."""
    rng = random.Random(seed)
    params = {
        "sort_by": rng.choice(DISCOVER_SORTS),
        "without_genres": _without_genres(),
        "include_adult": "false",
        "language": "ko-KR",
        "vote_count.gte": DISCOVER_MIN_VOTES,
        "region": "KR",                         # 한국 개봉일 기준으로 본다
        "with_release_type": "2|3",             # 극장 개봉만
        "release_date.gte": SINCE_DATE,
        "release_date.lte": TODAY,
    }
    pool = _discover_pool(params, max_page=30, rng=rng)
    got = _take(pool, n, rng, upcoming=False)
    if len(got) < n:
        print(f"후보가 모자라 {len(got)}편만 뽑았다. 이미 쓴 영화를 빼고 남은 것이 적다")
    return got


def pick_upcoming(n: int = 5, seed: int | None = None, months: int = 12) -> list[dict]:
    """아직 개봉하지 않은 영화를 무작위로 뽑는다.
    개봉 예정작은 수가 적어서 기간을 열두 달로 넓게 잡는다."""
    rng = random.Random(seed)
    until = (date.today() + timedelta(days=30 * months)).isoformat()
    params = {
        "sort_by": "popularity.desc",
        "without_genres": _without_genres(),
        "include_adult": "false",
        "language": "ko-KR",
        "region": "KR",
        "with_release_type": "1|2|3|4",   # 예정작은 시사회·디지털로만 적힌 경우가 많다
        "release_date.gte": TODAY,
        "release_date.lte": until,
    }
    pool = _discover_pool(params, max_page=15, rng=rng)
    got = _take(pool, n, rng, upcoming=True)
    if len(got) < n:
        print(f"개봉 예정작 후보가 모자라 {len(got)}편만 뽑았다. "
              f"months를 늘리거나 reset_used()로 기록을 비운다")
    return got


def reset_used():
    """뽑은 기록을 비운다. 같은 영화를 다시 쓰고 싶을 때 부른다."""
    USED.clear()
    print("뽑은 기록을 비웠다")

