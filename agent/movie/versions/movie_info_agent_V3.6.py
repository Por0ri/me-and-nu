def shape_form_check(body: str, m: Material) -> list[str]:
    """V2.5: 글의 꼴. 문장 길이가 다 비슷한가, 같은 주어로 문단을 여는가, 사실이 한 문단에 몰렸는가."""
    bad = []
    sents = [x.strip() for x in re.split(r"(?<=[.!?…])\s+", body) if len(x.strip()) >= 8]
    if SHAPE_LENGTH_CV and len(sents) >= 10:
        ls = [len(x) for x in sents]
        mean = sum(ls) / len(ls)
        sd = (sum((x - mean) ** 2 for x in ls) / len(ls)) ** 0.5
        if mean and sd / mean < SHAPE_LENGTH_CV:
            bad.append(f"문장 길이가 다 비슷하다 (편차 {sd / mean:.2f}). 짧은 문장과 긴 문장을 섞는다")
    paras = [x.strip() for x in body.split("\n") if x.strip()]
    openers = ("『" + m.title, "《" + m.title, m.title, "영화 『", "영화 《", "이 영화")
    title_open = sum(1 for x in paras if x.startswith(openers))
    if title_open >= 3:
        bad.append(f"영화 제목이나 '이 영화'로 문단을 {title_open}번 열었다. 두 번까지다")
    # V3.1: 관람 정보는 마지막 문단에 모은다. 앞 문단에 상영시간 · 등급이 나오거나, 마지막 문단에 정보가 없으면 잡는다
    if len(paras) >= 2:
        for i, x in enumerate(paras[:-1], 1):
            if re.search(r"\d+\s*분(?!기|야|의 ?\d)", x) or re.search(r"관람가|관람 등급|\d+세 이상", x):
                bad.append(f"{i}문단에 상영시간이나 등급이 나왔다. 관람 정보는 마지막 문단으로 옮긴다")
                break
        last = paras[-1]
        want = {"개봉": bool(m.release_date or m.upcoming or m.rerelease), "상영시간": bool(m.runtime_min),
                "등급": bool(m.rating), "출연진": bool(m.cast)}
        got = {"개봉": bool(re.search(r"개봉|\d{4}년\s*\d{1,2}월", last)), "상영시간": bool(re.search(r"\d+\s*분", last)),
               "등급": bool(re.search(r"관람가|등급|\d+세", last)), "출연진": any(c and c in last for c in (m.cast or [])[:8])}
        have = [k for k, v in want.items() if v]
        hit = [k for k in have if got[k]]
        if have and len(hit) < min(2, len(have)):
            bad.append("마지막 문단에 관람 정보가 없다. 개봉일 · 상영시간 · 등급 · 출연진 중 재료에 있는 것을 마지막 문단에 모은다")
    # V3.2: 반응 딱지 · 반응 문장으로 끝난 글
    if re.search(r"대중\s*평가(는|은|에는|가)\s", body):
        bad.append("'대중 평가는' 딱지를 붙였다. 평이 갈린다 · 좋게 본 사람이 많다처럼 다른 사실과 이어지는 문장 안에 넣는다")
    tail = [x for x in re.split(r"(?<=[.!?…])\s+", body.strip()) if x.strip()]
    last_clause = re.split(r",|지만|어도|는데|으나", tail[-1])[-1] if tail else ""   # "평은 갈렸어도, 불은 꺼지지 않는다"는 된다
    if last_clause and any(k in last_clause for k in RECEPTION_KEYS + ("대중 평가", "대중의 평가")):
        bad.append("글이 대중 평가 문장으로 끝났다. 마지막 문장은 앞 이야기로 돌아가 글을 닫는다")
    # V3.4: 같은 정보 되풀이 · 관람 정보로 끝난 글 (PM 9/29)
    bad += 정보되풀이(body, m)
    return bad


def _괄호뺌(x: str) -> str:
    return re.sub(r"\([^)]*\)", "", x)


_갈래틀 = re.compile(r"장르|갈래|요소|영화로|드라마로|드라마다|드라마이며|작품으로|결합|엮은|엮어|바탕으로 한|을 담|를 담|섞")


def _정보표시(x: str, m: Material) -> set:
    """문장 하나에 든 관람 정보 종류. 괄호 안(배우 소개)은 안 본다."""
    t = _괄호뺌(x)
    got = set()
    if (m.runtime_min and re.search(rf"(?<!\d){m.runtime_min}\s*분", t)) or re.search(r"상영\s*시간|러닝\s*타임", t):
        got.add("상영시간")
    if re.search(r"관람가|관람\s*등급|\d+세\s*이상|성인\s*등급|청소년\s*관람", t):
        got.add("등급")
    rd, fr = m.release_date or "", m.first_release or ""
    if (rd and rd[:4] + "년" in t and re.search(r"개봉|극장|재개봉|걸렸|걸린|관객을 만", t)) or (fr and fr[:4] != rd[:4] and fr[:4] + "년" in t):
        got.add("개봉 · 제작 연도")
    gs = [g for g in (m.genres or []) if g and g in t]
    if len(gs) >= 2 or (gs and _갈래틀.search(t)):
        got.add("갈래")
    return got


def 정보되풀이(body: str, m: Material) -> list[str]:
    """V3.4: 같은 관람 정보가 두 문장에 나오면 잡는다. 끝 문장이 관람 정보면 잡는다.
    9/29 저장 글 59편을 워크플로 에이전트가 표시한 정답지와 맞춰 기준을 정했다(정보 되풀이 맞게 24 · 놓침 16 · 끝 문장 맞게 8 · 잘못 0)."""
    bad = []
    ss = [x.strip() for x in re.split(r"(?<=[.!?…])\s+|\n+", body.strip()) if x.strip()]
    본 = {}
    for x in ss:
        for k in _정보표시(x, m):
            본.setdefault(k, []).append(x)
    for k, xs in 본.items():
        if len(xs) >= 2:
            bad.append(f"같은 정보 되풀이: {k}을(를) 두 번 적었다 ('{xs[0][:25]}…' / '{xs[1][:25]}…'). 한 번만 쓴다")
    for c in [c for c in (m.cast or [])[:8] if c]:
        같은 = [x for x in ss if c in _괄호뺌(x)]
        if len(같은) >= 2:
            bad.append(f"같은 정보 되풀이: 출연진({c})을 두 번 적었다 ('{같은[0][:25]}…' / '{같은[1][:25]}…'). 출연진은 마지막 문단에 한 번만 쓴다")
            break
    if ss:
        끝 = re.split(r",|지만|어도|는데|으나", ss[-1])[-1]
        종류 = _정보표시(끝, m)
        if sum(1 for c in (m.cast or [])[:8] if c and c in _괄호뺌(ss[-1])) >= 2:   # 출연진 목록은 쉼표로 이어져서 끝 문장 전체를 본다
            종류.add("출연진")
        if 종류:
            bad.append(f"마지막 문장이 관람 정보({' · '.join(sorted(종류))})로 끝났다. 마지막 문장은 앞 이야기로 돌아가 글을 닫는다")
    return bad

