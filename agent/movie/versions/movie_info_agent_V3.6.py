async def score(article: Article, order: WriteOrder,
                prev: dict | None = None, round_no: int = 1, kind: str = "첫 판") -> JudgeScore:
    before = (prev_text(prev) + "\n\n") if (REMEMBER_PREVIOUS and prev) else ""
    user = (
        f"{before}[배정 토픽] {order.topic}\n"
        f"[배정 유형] 정보 전달\n"
        f"[개봉 전 영화인가] {'그렇다' if order.material.upcoming else '아니다'}\n\n"
        f"[주문]\n{order_text(order)}\n\n"
        + (f"[독자의 질문] {order.brief.question}\n[답] {order.brief.answer}\n\n" if order.brief and order.brief.question else "") +
        f"[재료]\n{material_to_text(order.material)}\n\n"
        f"{this_head('[이번 글]', round_no, kind, prev)}\n제목: {article.title}\n\n{article.body}\n\n"
        f"[붙은 출처]\n" + "\n".join(article.sources)
    )
    result = await judge.run(user, usage_limits=_usage_limits)
    return result.output


def judge_total(s: JudgeScore) -> int:
    """V2.4: 최고 판을 고를 때 쓰는 합계. 통과 방향으로 더한다. 홍보성은 낮을수록 좋아서 뒤집는다."""
    return s.topic_fit + s.form_fit + s.element_fit + s.completeness + (6 - s.promo) - s.unsourced_claims

# ## 셀 11 — 업로드 규칙 (LLM 없이 코드로)

def verdict(s: JudgeScore) -> tuple[str, str]:
    drop, again = [], []

    def band(name, value, pass_line, drop_line):
        if value >= pass_line: return
        if value <= drop_line: drop.append(f"{name} {value}점")
        else:                  again.append(f"{name} {value}점")

    band("토픽 적합도", s.topic_fit,    PASS["topic_fit"],    2)
    band("유형 일치",   s.form_fit,     PASS["form_fit"],     2)
    band("요소 포함",   s.element_fit,  PASS["element_fit"],  2)
    band("글 완성도",   s.completeness, PASS["completeness"], 1)

    if s.promo >= 5:
        drop.append(f"홍보성 {s.promo}점")
    elif s.promo > PASS["promo"]:
        again.append(f"홍보성 {s.promo}점")

    if s.unsourced_claims > UNSOURCED_REWRITE:
        drop.append(f"기본 사실이 재료와 어긋난 문장 {s.unsourced_claims}개")
    elif s.unsourced_claims > UNSOURCED_PASS:
        again.append(f"기본 사실이 재료와 어긋난 문장 {s.unsourced_claims}개")

    if s.spoiler:
        again.append("결말을 밝혔다")

    if drop:  return "탈락", " / ".join(drop) + " — " + s.reason
    if again: return "다시쓰기", " / ".join(again) + " — " + s.reason
    return "올림", ""

# ## 셀 12 — 고치는 에이전트 (Pydantic AI)

FIXER_SYSTEM = """
너는 이미 쓴 글에서 지적된 곳만 고친다. 글을 새로 쓰지 않는다.

문장을 지우지 않는다. 지적된 표현을 다른 표현으로 바꾼다.
  지적: 감상이 섞였다 → 그 문장을 지우는 게 아니라 사실을 말하는 문장으로 바꾼다
  지적: 영문이 남았다 → 그 이름만 한글로 바꾼다
문단 하나가 두 문장 아래로 내려가면 안 된다. 그렇게 되면 지우지 말고 바꾼다.
글 전체 길이를 원래보다 줄이지 않는다. 분량 하한 아래로 내려가면 안 된다.

지적되지 않은 문장은 한 글자도 건드리지 않는다.
문단 순서를 바꾸지 않는다. 문단을 합치거나 나누지 않는다.
관람 정보를 마지막 문단으로 옮기라고 지적됐으면 그 사실만 앞 문단에서 빼서 마지막 문단에 문장으로 넣는다. 마지막 문단이 정보 문단이 아니면 끝에 정보 문단 하나를 붙인다.
지적을 고치느라 다른 곳이 어긋나면, 그 자리까지만 최소로 손본다.

분량이 지적됐으면 그 문단 안에서 늘리거나 줄인다. 새 문단을 만들지 않는다.
'글이 짧다'고 지적됐으면 [정리된 재료]의 쓸 거리 · 주변 이야기 · 인물 · 어디에서 나왔는지에서 아직 안 쓴 사실을 그 문단에 문장으로 보탠다. 같은 말을 다른 말로 되풀이해 늘리지 않는다. (V3.6)
문장을 빼서 분량이 모자라면 재료에서 아직 안 쓴 사실로 채운다. 이미 쓴 정보(출연진 · 개봉일 · 상영시간 · 등급 · 갈래)를 다시 적어 채우지 않는다. (V3.4)
마지막 문장을 빼게 되면 재료 안에서 앞 이야기로 돌아가 닫는 새 문장을 쓴다. 글을 관람 정보로 끝내지 않는다. (V3.4)
문장이 짧다고 지적됐으면 앞뒤 문장을 이어 붙인다. 내용을 더 넣지 않는다.
영문 표기가 남았다고 지적됐으면 그 이름만 한글로 바꾼다.
사실이 틀렸다고 지적됐으면 [정리된 재료]에 맞게 그 문장만 고친다.
재료에 없으면 그 문장을 뺀다. 지어내서 채우지 않는다.

문체는 원래 글을 따른다. 존댓말을 쓰지 않는다. 느낌표를 쓰지 않는다.
무엇을 어떻게 고쳤는지 한 줄씩 적는다.
"""

fixer = Agent(
    FIXER_MODEL,
    output_type=Fix,
    system_prompt=FIXER_SYSTEM,
    model_settings=_model_settings,
    retries=1,
)


async def fix(article: Article, order: WriteOrder, reasons: list[str]) -> Article:
    body = (brief_to_text(order.brief) if order.brief
            else material_to_text(order.material))
    user = (
        "[지적된 것]\n" + "\n".join(f"- {r}" for r in reasons) +
        f"\n\n[분량] {MIN_CHARS}자에서 {MAX_CHARS}자 사이다." +
        f"\n\n[정리된 재료]\n{body}" +
        f"\n\n[고칠 글]\n{article.body}"
    )
    out = (await fixer.run(user, usage_limits=_usage_limits)).output
    return Article(title=article.title, body=out.body,
                   sources=list(order.material.source_links))

