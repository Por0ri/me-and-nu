def genre_ok(m: Material) -> tuple[bool, str]:
    """갈래와 성인물 표시로 거른다. 등급으로는 거르지 않는다."""
    if m.adult:
        return False, "TMDB가 성인물로 표시한 항목이다"
    hit = set(m.genres) & EXCLUDE_GENRES
    if hit:
        return False, f"제외 갈래다 ({', '.join(sorted(hit))})"
    return True, ""


def date_ok(m: Material) -> tuple[bool, str]:
    """한국 극장에 2020년 1월 1일 뒤에 걸린 것만 다룬다.
    재개봉이면 옛날 영화도 통과한다. 개봉 예정작도 통과한다."""
    if not m.release_date:
        return False, "한국 극장 개봉 기록이 없다"
    if m.release_date < SINCE_DATE:
        return False, f"한국에서 {SINCE_DATE} 앞에 걸린 뒤 다시 걸린 적이 없다 ({m.release_date})"
    return True, ""


def enough_material(m: Material) -> tuple[bool, str]:
    """코드는 아무것도 없는 것만 뺀다. 줄거리가 짧은 건 재료 판정 에이전트가 본다."""
    if not m.synopsis and not m.context:
        return False, "줄거리도 주변 이야기도 없다"
    if not m.director and not m.genres:
        return False, "감독과 갈래가 모두 없다"
    return True, ""


def material_to_text(m: Material) -> str:
    rows = []
    def add(label, value):
        if value:
            rows.append(f"{label}: {value}")

    add("제목", m.title)
    if m.first_release:
        rows.append(f"처음 개봉(제작 연도): {m.first_release}")
    때 = (" — 아직 개봉하지 않았다. 앞으로 개봉한다고 쓴다" if m.upcoming
          else " — 이미 개봉했다. 과거형으로 쓴다(개봉했다 · 극장에 걸렸다). '걸린다' · '개봉한다'로 쓰지 않는다")   # V3.3
    if m.rerelease:
        rows.append(f"한국 개봉: {m.release_date} — 재개봉이다. "
                    f"{m.first_release[:4]}년 작품이 {m.release_date[:4]}년에 다시 걸렸다" + 때)
    elif getattr(m, "late_kr", False):
        rows.append(f"한국 개봉: {m.release_date} — {m.first_release[:4]}년 작품이 {m.release_date[:4]}년 한국 극장에 걸렸다. "
                    "전에 한국에서 개봉한 적이 있는지는 재료에 없다. '다시' · '처음'이라고 단정하지 않는다" + 때)
    else:
        rows.append(f"한국 개봉: {m.release_date or '정보 없음'}" + (때 if m.release_date else ""))
    add("감독", m.director)
    add("출연", ", ".join(m.cast))
    add("갈래", " · ".join(m.genres))
    add("상영시간", f"{m.runtime_min}분" if m.runtime_min else None)
    add("등급", m.rating)
    add("원작", m.source_work)
    add("시리즈 용어집", m.series or "")
    add("감독이 이 영화보다 앞에 만든 것", ", ".join(m.director_past_works))
    add("감독이 이 영화보다 뒤에 만든 것", ", ".join(m.director_later_works))
    add("줄거리", m.synopsis)

    if m.reception:
        rows.append(f"대중 평가 갈래: {m.reception}")     # 출처 · 날짜 · 점수는 본문에 못 가니 안 넘긴다
    else:
        rows.append("대중 평가 갈래: 없음 — 대중 평가를 쓰지 않는다")

    if m.context:
        rows.append(f"주변 이야기 (출처: {m.context_source}):\n{m.context}")
    else:
        rows.append("주변 이야기: 재료 없음 — 확실히 아는 것만 쓴다. 없으면 이 자리를 비운다")
    return "\n".join(rows)


