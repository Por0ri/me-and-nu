def _secret(name: str) -> str:
    v = os.environ.get(name)
    if not v or not v.strip():
        raise RuntimeError(
            f"환경변수 '{name}'이 없다. agent/.env 파일에 {name}=... 을 적거나 "
            f"셸에서 환경변수로 넣는다. (agent/.env.example 참고)"
        )
    return v.strip()


